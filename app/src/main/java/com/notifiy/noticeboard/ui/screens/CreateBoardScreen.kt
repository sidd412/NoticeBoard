//                {
//                    Column(
//                        modifier = Modifier.padding(16.dp)
//                    ) {
//                        Text(
//                            text = "Subscription Information",
//                            fontSize = 16.sp,
//                            fontWeight = FontWeight.Bold,
//                            color = MaterialTheme.colorScheme.onSurfaceVariant
//                        )
//                        Spacer(modifier = Modifier.height(8.dp))
//                        Text(
//                            text = "Your notice board will be created with a free subscription. You can upgrade to premium later for additional features.",
//                            fontSize = 14.sp,
//                            color = MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.8f)
//                        )
//                        Spacer(modifier = Modifier.height(12.dp))
//                        Button(
//                            onClick = {
//                                // TODO: Navigate to subscription page
//                            },
//                            modifier = Modifier.fillMaxWidth(),
//                            colors = ButtonDefaults.buttonColors(
//                                containerColor = MaterialTheme.colorScheme.primary
//                            )
//                        ) {
//                            Text("View Subscription Plans")
//                        }
//                    }
//                }
//            }
        }

        // Snackbar Host
        SnackbarHost(
            hostState = snackbarHostState,
            modifier = Modifier
                .align(Alignment.BottomCenter)
                .padding(bottom = 40.dp)
        )

        // Confirmation Dialog
        if (showConfirmationDialog) {
            AlertDialog(
                onDismissRequest = { showConfirmationDialog = false },
                title = { Text("Confirm Details") },
                text = { 
                    Text("Please review your details carefully:\n\n" +
                         "Organization: $organizationName\n" +
                         "Location: $organizationLocation\n" +
                         "Email: $organizationEmail\n" +
                         "WhatsApp: $organizationWhatsapp\n\n" +
                         "We will generate a unique 10-character code based on your organization name and location. " +
                         "This code cannot be changed once generated.")
                },
                confirmButton = {
                    TextButton(
                        onClick = {
                            showConfirmationDialog = false
                            isGeneratingCode = true
                            // Generate code based on org name and location
                            val generatedCode = generateSmartCode(organizationName, organizationLocation)
                            organizationCode = generatedCode
                            isCodeGenerated = true
                            isGeneratingCode = false
                        }
                    ) {
                        Text("Continue")
                    }
                },
                dismissButton = {
                    TextButton(
                        onClick = { showConfirmationDialog = false }
                    ) {
                        Text("Recheck")
                    }
                }
            )
        }

    }
}
